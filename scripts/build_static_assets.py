"""Bundle public schemas, prompts and reviewed claims for a serverless Static Space.

Never reads .env/API_KEY.txt. Run again after changing models/prompts/claims.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from glowpick.models import UserInput, Extraction, ModelAnalysis, ReviewedClaim


def build():
    schemas = {model.__name__: model.model_json_schema()
               for model in (UserInput, Extraction, ModelAnalysis, ReviewedClaim)}
    values = {
        "SCHEMAS": schemas,
        "CLAIMS": json.loads((ROOT / "data/reviewed_claims.json").read_text(encoding="utf-8")),
        "GUIDANCE": json.loads((ROOT / "data/reviewed_guidance.json").read_text(encoding="utf-8")),
        "RETAIL_LISTINGS": json.loads((ROOT / "data/retail_listings.json").read_text(encoding="utf-8")),
        "EXTRACT_PROMPT": (ROOT / "prompts/extract.txt").read_text(encoding="utf-8"),
        "EXPLAIN_PROMPT": (ROOT / "prompts/explain.txt").read_text(encoding="utf-8"),
        "MOCK_EXTRACTION": json.loads((ROOT / "fixtures/mock_extraction.json").read_text(encoding="utf-8")),
    }
    text = "// Generated by scripts/build_static_assets.py. Public data only; contains no API key.\n"
    text += "\n".join(f"export const {name} = {json.dumps(value, ensure_ascii=False, indent=2)};"
                      for name, value in values.items()) + "\n"
    destination = ROOT / "BeautyAI/ai-assets.js"
    destination.write_text(text, encoding="utf-8", newline="\n")
    print("Built BeautyAI/ai-assets.js from public source files; credentials were not read.")


if __name__ == "__main__":
    build()
